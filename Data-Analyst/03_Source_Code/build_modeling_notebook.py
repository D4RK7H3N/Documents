        "print('Silhouette:', [round(s, 3) for s in silhouettes])\n"
        "print('Best silhouette at k =', best_k)\n"
        "\n"
        "final_kmeans = KMeans(n_clusters=best_k, random_state=RANDOM_STATE, n_init=10).fit(scaled)\n"
