"""Build the Phase 2 cleaning notebook from explicit, reviewable cell sources."""

from pathlib import Path

import nbformat as nbf

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "03_Source_Code" / "data_cleaning.ipynb"

md = nbf.v4.new_markdown_cell
code = nbf.v4.new_code_cell

cells = [
    md(
        "# Phase 2 - Data Cleaning and Transformation\n"
        "\n"
        "**Integrity notice:** the source data is synthetic (see `02_Datasets/DATA_PROVENANCE.md`). "
        "The raw file is never modified; every transformation writes to `cleaned_dataset.csv`.\n"
        "\n"
        "Every action is appended to `cleaning_log.csv` with the number of affected rows and the "
        "justification. Logging the *why* matters: it lets a reviewer audit each decision rather "
        "than trusting a silent pipeline."
    ),
    code(
        "from pathlib import Path\n"
        "\n"
        "import numpy as np\n"
        "import pandas as pd\n"
        "\n"
        "ROOT = Path.cwd()\n"
        "if not (ROOT / '02_Datasets').exists():\n"
        "    ROOT = ROOT.parent\n"
        "RAW = ROOT / '02_Datasets' / 'raw_dataset.csv'\n"
        "CLEAN = ROOT / '02_Datasets' / 'cleaned_dataset.csv'\n"
        "LOG = ROOT / '02_Datasets' / 'cleaning_log.csv'\n"
        "\n"
        "df = pd.read_csv(RAW)\n"
        "print('Raw shape:', df.shape)\n"
        "df.head()"
    ),
    md(
        "## 1. Duplicates and privacy\n"
        "\n"
        "Exact duplicate rows would double-count students and distort every statistic, so they are "
        "removed before any other step. `student_id` is a personal identifier; it is not needed for "
        "analysis, so it is dropped rather than merely masked (the safest privacy choice)."
    ),
    code(
        "cleaning_log = []\n"
        "\n"
        "\n"
        "def record(action, justification, rows_before, rows_after, affected):\n"
        "    cleaning_log.append({\n"
        "        'action': action,\n"
        "        'rows_affected': affected,\n"
        "        'rows_before': rows_before,\n"
        "        'rows_after': rows_after,\n"
        "        'justification': justification,\n"
        "    })\n"
        "\n"
        "\n"
        "before = len(df)\n"
        "n_duplicates = int(df.duplicated().sum())\n"
        "df = df.drop_duplicates().reset_index(drop=True)\n"
        "record('Remove exact duplicate rows',\n"
        "       'Duplicates double-count students and bias statistics.',\n"
        "       before, len(df), n_duplicates)\n"
        "print('Duplicates removed:', n_duplicates, '| shape:', df.shape)\n"
        "\n"
        "before = len(df)\n"
        "df = df.drop(columns=['student_id'])\n"
        "record('Drop student_id (PII)',\n"
        "       'Direct identifier unnecessary for analysis; removing it protects privacy.',\n"
        "       before, len(df), before)\n"
        "print('Columns after privacy step:', list(df.columns))"
    ),
    md(
        "## 2. Standardize categorical labels\n"
        "\n"
        "The raw profile showed 8 gender labels, 9 parental-education labels and 7 extracurricular "
        "labels, caused by case differences, abbreviations, trailing spaces and apostrophes. "
        "Grouping these into a single canonical label per concept prevents the same category being "
        "counted several times. Whitespace is stripped before mapping."
    ),
    code(
        "def standardize(series, mapping):\n"
        "    return series.astype(str).str.strip().replace(mapping)\n"
        "\n"
        "\n"
        "gender_map = {'male': 'Male', 'female': 'Female', 'M': 'Male', 'F': 'Female'}\n"
        "before_values = df['gender'].astype(str).str.strip()\n"
        "df['gender'] = standardize(df['gender'], gender_map)\n"
        "n_changed = int((before_values != df['gender']).sum())\n"
        "record('Standardize gender labels',\n"
        "       'Case and abbreviation variants otherwise fragment the same category.',\n"
        "       len(df), len(df), n_changed)\n"
        "print('Gender:', df['gender'].value_counts().to_dict())\n"
        "\n"
        "education_map = {\n"
        "    'bachelors': 'Bachelor', \"Bachelor's\": 'Bachelor',\n"
        "    'highschool': 'High School', 'phd': 'PhD',\n"
        "}\n"
        "before_values = df['parental_education'].astype(str).str.strip()\n"
        "df['parental_education'] = standardize(df['parental_education'], education_map)\n"
        "n_changed = int((before_values != df['parental_education']).sum())\n"
        "record('Standardize parental_education labels',\n"
        "       'Case, spacing and apostrophe variants otherwise fragment the same category.',\n"
        "       len(df), len(df), n_changed)\n"
        "print('Parental education:', df['parental_education'].value_counts().to_dict())\n"
        "\n"
        "extra_map = {'yes': 'Yes', 'Y': 'Yes', 'no': 'No', 'N': 'No'}\n"
        "before_values = df['extracurricular_activities'].astype(str).str.strip()\n"
        "df['extracurricular_activities'] = standardize(df['extracurricular_activities'], extra_map)\n"
        "n_changed = int((before_values != df['extracurricular_activities']).sum())\n"
        "record('Standardize extracurricular labels',\n"
        "       'Yes/No variants must be unified before group comparison.',\n"
        "       len(df), len(df), n_changed)\n"
        "print('Extracurricular:', df['extracurricular_activities'].value_counts().to_dict())"
    ),
    md(
        "## 3. Invalid ranges and statistical outliers\n"
        "\n"
        "Negative study hours and attendance above 100% are impossible, so they are treated as "
        "missing rather than silently kept. Implausibly large study hours are detected with the IQR "
        "rule (values above Q3 + 1.5 x IQR) and also set to missing. Converting bad values to "
        "missing keeps the affected rows instead of discarding otherwise useful information."
    ),
    code(
        "invalid_study = int((df['study_hours_per_week'] < 0).sum())\n"
        "df.loc[df['study_hours_per_week'] < 0, 'study_hours_per_week'] = np.nan\n"
        "record('Flag negative study hours as missing',\n"
        "       'Negative study time is impossible; keep the row but drop the invalid value.',\n"
        "       len(df), len(df), invalid_study)\n"
        "\n"
        "invalid_attendance = int((df['attendance_percentage'] > 100).sum())\n"
        "df.loc[df['attendance_percentage'] > 100, 'attendance_percentage'] = np.nan\n"
        "record('Flag attendance above 100 as missing',\n"
        "       'Attendance cannot exceed 100 percent.',\n"
        "       len(df), len(df), invalid_attendance)\n"
        "\n"
        "q1, q3 = df['study_hours_per_week'].quantile([0.25, 0.75])\n"
        "upper_bound = q3 + 1.5 * (q3 - q1)\n"
        "n_outliers = int((df['study_hours_per_week'] > upper_bound).sum())\n"
        "df.loc[df['study_hours_per_week'] > upper_bound, 'study_hours_per_week'] = np.nan\n"
        "record('Flag IQR study-hour outliers as missing',\n"
        "       'Values above Q3+1.5*IQR are implausible and would distort means and correlations.',\n"
        "       len(df), len(df), n_outliers)\n"
        "\n"
        "print(f'IQR upper bound = {upper_bound:.2f} hours; outliers flagged = {n_outliers}')\n"
        "print(f'Negative study hours = {invalid_study}; attendance > 100 = {invalid_attendance}')"
    ),
    md(
        "## 4. Impute remaining missing values\n"
        "\n"
        "Missing values in study hours, attendance and prior GPA are imputed with each column's "
        "median. The median is robust to the remaining skew and to extreme values, whereas the mean "
        "would be pulled by them. Dropping rows was rejected because it would discard roughly 9% of "
        "records and could bias the sample."
    ),
    code(
        "for column in ['study_hours_per_week', 'attendance_percentage', 'previous_gpa']:\n"
        "    n_missing = int(df[column].isna().sum())\n"
        "    median_value = df[column].median()\n"
        "    df[column] = df[column].fillna(median_value)\n"
        "    record(f'Impute {column} with median',\n"
        "           'Median is robust to skew; dropping rows would lose data and bias the sample.',\n"
        "           len(df), len(df), n_missing)\n"
        "    print(f'{column}: {n_missing} imputed, median = {median_value:.2f}')\n"
        "\n"
        "print('Remaining missing values:', int(df.isna().sum().sum()))"
    ),
    md(
        "## 5. Derived variables\n"
        "\n"
        "Four variables are engineered from the cleaned columns. `grade_band` gives a categorical "
        "performance outcome for group comparison and possible classification; `attendance_status` "
        "and `study_hours_category` turn continuous habits into interpretable groups; "
        "`academic_risk_index` standardizes and combines three predictors so lower values flag "
        "students who may need support. Thresholds are stated explicitly so they can be challenged."
    ),
    code(
        "df['grade_band'] = pd.cut(\n"
        "    df['final_score'],\n"
        "    bins=[-np.inf, 50, 70, 85, np.inf],\n"
        "    labels=['Fail', 'Pass', 'Credit', 'Distinction'],\n"
        ")\n"
        "record('Derive grade_band',\n"
        "       'Categorical performance outcome: <50 Fail, 50-70 Pass, 70-85 Credit, >85 Distinction.',\n"
        "       len(df), len(df), len(df))\n"
        "\n"
        "df['attendance_status'] = pd.cut(\n"
        "    df['attendance_percentage'],\n"
        "    bins=[-np.inf, 75, 90, np.inf],\n"
        "    labels=['Low', 'Moderate', 'High'],\n"
        ")\n"
        "record('Derive attendance_status',\n"
        "       'Groups attendance into Low (<75), Moderate (75-90), High (>90) for comparison.',\n"
        "       len(df), len(df), len(df))\n"
        "\n"
        "df['study_hours_category'] = pd.qcut(\n"
        "    df['study_hours_per_week'], q=3, labels=['Low', 'Moderate', 'High'], duplicates='drop'\n"
        ")\n"
        "record('Derive study_hours_category',\n"
        "       'Tertiles of study hours make dose-response comparison possible.',\n"
        "       len(df), len(df), len(df))\n"
        "\n"
        "components = [\n"
        "    (df['previous_gpa'] - df['previous_gpa'].mean()) / df['previous_gpa'].std(),\n"
        "    (df['attendance_percentage'] - df['attendance_percentage'].mean()) / df['attendance_percentage'].std(),\n"
        "    (df['study_hours_per_week'] - df['study_hours_per_week'].mean()) / df['study_hours_per_week'].std(),\n"
        "]\n"
        "df['academic_risk_index'] = (-sum(components) / len(components)).round(3)\n"
        "record('Derive academic_risk_index',\n"
        "       'Negative mean z-score of GPA, attendance and study hours; higher means higher risk.',\n"
        "       len(df), len(df), len(df))\n"
        "\n"
        "print(df[['grade_band', 'attendance_status', 'study_hours_category', 'academic_risk_index']].head())"
    ),
    md(
        "## 6. Validation and output\n"
        "\n"
        "Assertions verify that cleaning actually achieved its goals: no missing values, no "
        "duplicates, valid ranges, and no personal identifier. If any assertion fails the notebook "
        "stops rather than exporting a flawed dataset."
    ),
    code(
        "assert df.isna().sum().sum() == 0, 'Missing values remain'\n"
        "assert df.duplicated().sum() == 0, 'Duplicate rows remain'\n"
        "assert 'student_id' not in df.columns, 'Identifier not removed'\n"
        "assert df['attendance_percentage'].between(0, 100).all(), 'Invalid attendance remains'\n"
        "assert (df['study_hours_per_week'] >= 0).all(), 'Invalid study hours remain'\n"
        "\n"
        "print('All validation checks passed.')\n"
        "print('Final shape:', df.shape)\n"
        "print(df.dtypes.to_string())\n"
        "print('Numeric summary after cleaning:')\n"
        "print(df.describe().T.to_string())"
    ),
    code(
        "df.to_csv(CLEAN, index=False)\n"
        "pd.DataFrame(cleaning_log).to_csv(LOG, index=False)\n"
        "print('Wrote', CLEAN.relative_to(ROOT))\n"
        "print('Wrote', LOG.relative_to(ROOT))\n"
        "pd.DataFrame(cleaning_log)"
    ),
    md(
        "## Cleaning summary\n"
        "\n"
        "The cleaned dataset contains one row per student with no missing values, no duplicates and "
        "no direct identifier. The exact counts for every action are in `cleaning_log.csv`; the "
        "numbers quoted in the report are taken from this executed notebook, not typed by hand."
    ),
]

nb = nbf.v4.new_notebook(cells=cells)
nbf.write(nb, TARGET)
print(f"Built {TARGET.relative_to(ROOT)} with {len(cells)} cells")
